#!/bin/bash
# The call screen's files as the WordPlusUI plugin copies them into an app (`swift package wordplus-ui add`):
# Plugins/WordPlusUI/Embedded.swift, written from Sources/WordPlusRealtimeUI, and its tests from
# Tests/WordPlusRealtimeUITests as Tests/<file>. A plugin run on an Xcode project can't read another target's sources, so
# it carries them. Run after changing the screen or its tests; `--check` fails while the two differ.
set -euo pipefail
cd "$(dirname "$0")/.."

out=Plugins/WordPlusUI/Embedded.swift
version=1.0.2

render() {
    echo "// Generated by scripts/embed-ui.sh from Sources/WordPlusRealtimeUI: the call screen's files the WordPlusUI plugin"
    echo "// copies into an app. Not edited by hand: change the screen, then run the script."
    echo
    echo "let embeddedVersion = \"$version\""
    echo
    echo "let embeddedFiles: [ ( name: String, text: String ) ] = ["
    for file in Sources/WordPlusRealtimeUI/*.swift Tests/WordPlusRealtimeUITests/*.swift; do
        if grep -q '"""##' "$file"; then echo "$file holds \"\"\"##, which the embedding can't carry" >&2; exit 1; fi
        case "$file" in Tests/*) name="Tests/$(basename "$file")" ;; *) name="$(basename "$file")" ;; esac
        echo "    ( \"$name\", ##\"\"\""
        cat "$file"
        echo "\"\"\"## ),"
    done
    echo "]"
}

if [ "${1:-}" = "--check" ]; then
    if ! diff -q <(render) "$out" > /dev/null; then
        echo "$out differs from Sources/WordPlusRealtimeUI: run scripts/embed-ui.sh" >&2
        exit 1
    fi
    echo "$out is current"
else
    render > "$out"
    echo "wrote $out"
fi
